"""Generate src/qbridge/parsers/kevspec.py from the QNX SDP's own documentation.

Run on a machine with the QNX 8.0 SDP installed (developers only; the
generated file is committed, so users and CI never need the SDP):

    python tools/gen_kevspec.py [path-to-qnx800]

Sources, both shipped with the SDP:
  - the System Analysis Toolkit's "Current Trace Events and Data" table
    (com.qnx.doc.sat/topic/kercall_table_Events.html): per event, the fields
    emitted in fast and wide mode, which are 64-bit, and their print format
    (the "#Args" line: f = also in fast mode; D/H/S/P = 32-bit decimal, hex,
    string, pointer; E/X/Q = 64-bit decimal, hex, pointer);
  - <sys/kercalls.h>: kernel call numbers.

Only field names, widths, formats and numbers are taken; nothing is guessed.
Events the table does not describe are decoded by name only.
"""

from __future__ import annotations

import html
import pprint
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "qbridge" / "parsers" / "kevspec.py"


def _fields(text: str) -> list[str]:
    return [f.strip() for f in text.split(",") if f.strip()]


def _parse_field(f: str) -> tuple[str, int]:
    """'sync_p (64)' -> ('sync_p', 64); 'addr(64)' -> ('addr', 64)."""
    m = re.fullmatch(r"(.*?)\s*\(64\)", f)
    if m:
        return m[1].strip(), 64
    return f, 32


def _args(text: str) -> list[tuple[bool, str, str]]:
    """'MSG_SENDV, fHcoid, Dsparts' -> [(fast, fmt, name), ...] (first item is the call)."""
    out = []
    for a in _fields(text)[1:]:
        m = re.fullmatch(r"(f?)([A-Za-z])(.*)", a)
        if m:
            out.append((m[1] == "f", m[2], m[3]))
    return out


def blocks(doc: str):
    text = html.unescape(re.sub(r"<[^>]*>", "", doc))
    cur, key = None, None
    for raw in text.splitlines():
        line = raw.strip()
        m = re.match(r"^(Class|Event|Fast|Wide|Call|#Args):\s*(.*)$", line)
        if m:
            if m[1] == "Class":
                if cur:
                    yield cur
                cur = {}
            if cur is not None:
                key = m[1]
                cur[key] = m[2]
            continue
        if cur is not None and key in ("Fast", "Wide", "#Args") and line and not line.startswith("#"):
            cur[key] += " " + line        # a wrapped list
        else:
            key = None
    if cur:
        yield cur


def main() -> None:
    sdp = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "qnx800"
    doc = (sdp / "target/qnx/usr/help/eclipse/plugins/com.qnx.doc.sat/topic/"
           "kercall_table_Events.html").read_text(encoding="utf-8", errors="replace")
    hdr = (sdp / "target/qnx/usr/include/sys/kercalls.h").read_text(encoding="utf-8", errors="replace")
    numbers = {m[1]: int(m[2]) for m in re.finditer(r"#define\s+__KER_(\w+)\s+(\d+)\b", hdr)}

    kercalls: dict = {}
    for b in blocks(doc):
        cls = b.get("Class", "")
        if cls not in ("_NTO_TRACE_KERCALLENTER", "_NTO_TRACE_KERCALLEXIT"):
            continue
        m = re.fullmatch(r"__KER_(\w+?)(\|_NTO_TRACE_KERCALL64)?", b.get("Event", "").strip())
        if not m or m[1] not in numbers:
            continue
        fmts = {name: (fmt, fast) for fast, fmt, name in _args(b.get("#Args", ""))}
        entry = {}
        for mode in ("Fast", "Wide"):
            spec = b.get(mode, "N/A").strip()
            if spec in ("N/A", ""):
                continue
            fields = []
            for f in _fields(spec):
                name, bits = _parse_field(f)
                fmt = fmts.get(name, (None,))[0]
                if fmt is None:
                    fmt = "X" if bits == 64 else "D"
                fields.append((name, bits, fmt))
            entry[mode.lower()] = fields
        if entry:
            key = (numbers[m[1]], cls.endswith("EXIT"), bool(m[2]))
            kercalls.setdefault(key, entry)

    names = {n: k for k, n in numbers.items() if not k.startswith("BAD") or k == "BAD"}
    body = (
        '"""Kernel call names and trace event layouts, generated by tools/gen_kevspec.py\n'
        "from the QNX 8.0 SDP's System Analysis Toolkit event table and <sys/kercalls.h>.\n"
        'Do not edit by hand."""\n\n'
        "# kernel call number -> name (without __KER_)\n"
        f"KERCALL_NAMES = {pprint.pformat(dict(sorted(names.items())), width=100)}\n\n"
        "# (call number, is_exit, is_64bit) -> {'fast'|'wide': [(field, bits, fmt), ...]}\n"
        "# fmt: D/H/S/P 32-bit decimal/hex/string/pointer, E/X/Q 64-bit decimal/hex/pointer\n"
        f"KERCALL_LAYOUTS = {pprint.pformat(dict(sorted(kercalls.items())), width=100)}\n"
    )
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {len(names)} kernel call names, {len(kercalls)} layouts")


if __name__ == "__main__":
    main()
