"""Post-mortem crash analysis from QNX core files.

On QNX, the `dumper` service writes an ELF core file when a process dies
from a signal. On the qbridge reference image it runs as

    dumper -U 30:30 -d /data/var/dumper -M 1000 -D cores

so cores for root-owned processes land in /data/var/dumper/<program>.core
(overwritten on each crash). qbridge fetches the core and the matching
binary from the target, then runs the SDP's ntox86_64-gdb in batch mode
and turns its output into structured data.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

from . import qnxenv
from .target import Target, TargetError

CORE_DIRS = ["/data/var/dumper"]
GDB = "ntox86_64-gdb"
MARK = "@@QB "
# Fault addresses below one page are almost always a NULL pointer plus a field offset.
NULL_PAGE = 4096

SIGNALS = {4: "SIGILL", 5: "SIGTRAP", 6: "SIGABRT", 7: "SIGEMT", 8: "SIGFPE", 9: "SIGKILL",
           10: "SIGBUS", 11: "SIGSEGV", 12: "SIGSYS", 13: "SIGPIPE", 15: "SIGTERM"}


def cache_dir() -> Path:
    base = os.environ.get("QBRIDGE_CACHE") or (Path(os.environ.get("USERPROFILE") or Path.home()) / ".qbridge")
    return Path(base) / "cores"


# -- listing cores on the target -------------------------------------------

def list_cores(target: Target, dirs: list[str] | None = None) -> list[dict]:
    """Core files on the target, newest first."""
    dirs = dirs or CORE_DIRS
    globs = " ".join(f"{d}/*.core*" for d in dirs)
    r = target.run(["sh", "-c", f"stat -c '%n|%s|%Y' {globs} 2>/dev/null; true"])
    cores = []
    for line in r.stdout.splitlines():
        parts = line.strip().split("|")
        if len(parts) != 3 or not parts[1].isdigit():
            continue
        path, size, mtime = parts
        name = path.rsplit("/", 1)[-1]
        cores.append({"path": path, "program": name.split(".core")[0],
                      "bytes": int(size), "time": int(mtime)})
    cores.sort(key=lambda c: c["time"], reverse=True)
    return cores


# -- gdb ---------------------------------------------------------------------

def gdb_args(core: Path, binary: Path | None, qnx_target: str | None) -> list[str]:
    def fwd(p) -> str:
        return str(p).replace("\\", "/")

    ex = ["set pagination off", "set confirm off", "set width 0",
          "set print frame-arguments all"]
    if qnx_target:
        qt = fwd(qnx_target)
        sep = ";" if os.name == "nt" else ":"
        ex.append(f"set solib-search-path {qt}/x86_64/lib{sep}{qt}/x86_64/usr/lib")
    if binary:
        ex.append(f"file {fwd(binary)}")
    ex.append(f"core-file {fwd(core)}")
    if binary:
        ex += [
            f"echo {MARK}siginfo\\n", "p $_siginfo",
            f"echo {MARK}backtrace\\n", "bt full",
            f"echo {MARK}source\\n", "list",
            f"echo {MARK}threads\\n", "info threads",
            f"echo {MARK}all_threads\\n", "thread apply all bt",
        ]
    args = [GDB, "-nx", "-batch"]
    for e in ex:
        args += ["-ex", e]
    return args


def run_gdb(core: Path, binary: Path | None, timeout: float = 120) -> str:
    env = qnxenv.load()
    qt = next((v for k, v in env.items() if k.upper() == "QNX_TARGET"), None)
    path = next((v for k, v in env.items() if k.upper() == "PATH"), None)
    exe = shutil.which(GDB, path=path)
    if not exe:
        raise TargetError(f"{GDB} not found in the QNX SDP")
    args = gdb_args(core, binary, qt)
    p = subprocess.run(args, executable=exe, env=env, capture_output=True, text=True,
                       errors="replace", timeout=timeout)
    return (p.stdout or "") + (p.stderr or "")


# -- parsing gdb output -------------------------------------------------------

_GENERATED_RE = re.compile(r"^Core was generated by `(?P<cmd>[^']*)'")
_TERMINATED_RE = re.compile(r"^Program terminated with signal (?P<sig>\w+), (?P<desc>.+)\.$")
_FRAME_RE = re.compile(
    r"^#(?P<level>\d+)\s+(?:(?P<addr>0x[0-9a-f]+) in )?(?P<func>[^\s(]+) \((?P<args>.*?)\)"
    r"(?: at (?P<file>.+):(?P<line>\d+)| from (?P<lib>\S+))?\s*$"
)
_LOCAL_RE = re.compile(r"^\s{8}(?P<name>[\w.$]+) = (?P<value>.*)$")
_SIGNO_RE = re.compile(r"si_signo = (\d+)")
_SICODE_RE = re.compile(r"si_code = (-?\d+)")
_FAULT_ADDR_RE = re.compile(r"__fault = \{[^}]*__addr = (0x[0-9a-f]+)")
_FAULT_IP_RE = re.compile(r"__fltip = (0x[0-9a-f]+)")


def _sections(text: str) -> tuple[list[str], dict[str, list[str]]]:
    head: list[str] = []
    secs: dict[str, list[str]] = {}
    cur = head
    for line in text.splitlines():
        if line.startswith(MARK):
            cur = secs.setdefault(line[len(MARK):].strip(), [])
        else:
            cur.append(line)
    return head, secs


def _parse_args(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    depth, cur = 0, ""
    for ch in text + ",":
        if ch in "{([":
            depth += 1
        elif ch in "})]":
            depth -= 1
        if ch == "," and depth == 0:
            if "=" in cur:
                k, v = cur.split("=", 1)
                out[k.strip()] = v.strip()
            cur = ""
        else:
            cur += ch
    return out


def parse_backtrace(lines: list[str]) -> list[dict]:
    frames: list[dict] = []
    last_local: str | None = None
    for line in lines:
        m = _FRAME_RE.match(line)
        if m:
            frames.append({
                "level": int(m["level"]),
                "function": m["func"],
                "args": _parse_args(m["args"]),
                "file": m["file"],
                "line": int(m["line"]) if m["line"] else None,
                "library": m["lib"],
                "address": m["addr"],
                "locals": {},
            })
            last_local = None
            continue
        if not frames:
            continue
        m = _LOCAL_RE.match(line)
        if m:
            frames[-1]["locals"][m["name"]] = m["value"]
            last_local = m["name"]
        elif last_local and line.startswith(" " * 9):
            frames[-1]["locals"][last_local] += " " + line.strip()
    for f in frames:
        for k in [k for k, v in f.items() if v is None]:
            del f[k]
    return frames


def parse_gdb(text: str) -> dict:
    head, secs = _sections(text)
    out: dict = {}
    for line in head:
        if m := _GENERATED_RE.match(line):
            out["command"] = m["cmd"]
            out["program"] = m["cmd"].split()[0] if m["cmd"] else None
        elif m := _TERMINATED_RE.match(line):
            out["signal"] = m["sig"]
            out["signal_description"] = m["desc"]

    sig = " ".join(secs.get("siginfo", []))
    if m := _SIGNO_RE.search(sig):
        out["signo"] = int(m[1])
        out.setdefault("signal", SIGNALS.get(int(m[1]), f"signal {m[1]}"))
    if m := _SICODE_RE.search(sig):
        out["si_code"] = int(m[1])
    if m := _FAULT_ADDR_RE.search(sig):
        out["fault_address"] = m[1]
    if m := _FAULT_IP_RE.search(sig):
        out["fault_ip"] = m[1]

    out["frames"] = parse_backtrace(secs.get("backtrace", []))
    src = [l for l in secs.get("source", []) if re.match(r"^\d+\t", l)]
    if src:
        out["source"] = "\n".join(src)
    others = secs.get("all_threads", [])
    out["thread_count"] = sum(1 for l in secs.get("threads", []) if re.match(r"^[ *]\s+\d+\s", l))
    if out["thread_count"] > 1:
        out["all_threads"] = "\n".join(l for l in others if l.strip())
    out["summary"] = summarise(out)
    return out


def summarise(c: dict) -> str:
    parts = [f"{c.get('program') or 'process'} died with {c.get('signal', 'a signal')}"]
    top = next((f for f in c.get("frames", []) if "file" in f), None)
    if top:
        parts.append(f"in {top['function']}() at {top['file']}:{top['line']}")
    elif c.get("frames"):
        parts.append(f"in {c['frames'][0]['function']}()")
    s = " ".join(parts) + "."
    addr = c.get("fault_address")
    if addr and c.get("signal") in ("SIGSEGV", "SIGBUS"):
        a = int(addr, 16)
        if a < NULL_PAGE:
            s += f" Fault address {addr} is in the first page: a NULL pointer dereference" \
                 f"{f' (field at offset {a})' if a else ''}."
            if top:
                nulls = [k for k, v in top.get("locals", {}).items() if v.strip() == "0x0"]
                nulls += [k for k, v in top.get("args", {}).items() if v.strip() == "0x0"]
                if nulls:
                    s += f" NULL pointer(s) in that frame: {', '.join(nulls)}."
        else:
            s += f" Fault address {addr}."
    return s


# -- the tool -----------------------------------------------------------------

def analyse(target: Target, core: str | None = None, binary: str | None = None) -> dict:
    cores = list_cores(target)
    if not cores:
        return {"found": False, "message": f"no core files in {', '.join(CORE_DIRS)}"}
    if core:
        pick = next((c for c in cores if c["path"] == core or c["program"] == core), None)
        if not pick:
            return {"found": False, "message": f"no core matching {core!r}",
                    "cores": cores}
    else:
        pick = cores[0]

    cdir = cache_dir()
    local_core = cdir / f"{pick['program']}.{pick['time']}.core"
    if not local_core.exists():
        target.get(pick["path"], local_core)

    if binary:
        local_bin = Path(binary).resolve()
        if not local_bin.is_file():
            raise FileNotFoundError(f"{local_bin} is not a file")
    else:
        # Ask gdb which program made the core, then fetch that exact binary.
        head = parse_gdb(run_gdb(local_core, None))
        remote_bin = head.get("program")
        if not remote_bin or not remote_bin.startswith("/"):
            raise TargetError("could not tell which program made the core; pass binary=")
        local_bin = cdir / f"{pick['program']}.{pick['time']}.bin"
        if not local_bin.exists():
            target.get(remote_bin, local_bin)

    result = parse_gdb(run_gdb(local_core, local_bin))
    result.update({"found": True, "core": pick, "binary": str(local_bin),
                   "other_cores": cores[1:6]})
    return result
